using System;
using System.IO;
using System.Linq;
using System.Text;
using Typedown.WinUI.Services.Conversion;
using Xunit;

namespace Caret.ConverterTests
{
    // Peru's electronic invoice (SUNAT, UBL 2.1): the same UBL structure as the Colombian pack reads, with the codes of SUNAT (Services/Conversion/XmlPeru.cs).
    // The samples in samples/ are invented.
    public class PeruTests
    {
        private static string Sample(string name, string language = "en") =>
            DocumentConverter.Convert(Path.Combine(TestPaths.Samples, name), new ConversionOptions { Language = language }).Markdown;

        private static string Read(string xml, string language = "en")
        {
            var work = TestPaths.NewTempFolder();
            try
            {
                var path = Path.Combine(work, "test.xml");
                File.WriteAllText(path, xml, new UTF8Encoding(false));
                return DocumentConverter.Convert(path, new ConversionOptions { Language = language }).Markdown;
            }
            finally { Directory.Delete(work, true); }
        }

        [Fact]
        public void An_invoice_reads_with_the_codes_of_SUNAT_and_the_RUC_has_no_check_digit()
        {
            var md = Sample("pe-factura.xml");
            Assert.StartsWith("# Electronic invoice F001-123", md);
            Assert.Contains("> 2.1 · 0101 (Domestic sale)", md);
            // schemeID="6" is the type of document (catalog 06), not a check digit as in Colombia
            Assert.Contains("- **Tax ID:** 20000000001 (RUC)", md);
            Assert.DoesNotContain("20000000001-6", md);
            Assert.Contains("- **Address:** AV. DE PRUEBA 100, URB. EJEMPLO, MIRAFLORES, LIMA, LIMA, PE", md);
            // the legends of catalog 52, the text as it was written
            Assert.Contains("- CIENTO OCHENTA Y UNO CON 04/100 SOLES (Amount in words)", md);
            Assert.Contains("(Internal code generated by the invoicing software)", md);
            // the affectation of the IGV of each line (catalog 07) and the types of tax (catalog 05)
            Assert.Contains("| 1 | Cuaderno de muestra | 4 | NIU | 32.00 PEN | 128.00 PEN | 10 · Taxed - onerous operation |", md);
            Assert.Contains("| 2 | Servicio de ejemplo | 1 | ZZ | 30.00 PEN | 30.00 PEN | 20 · Exonerated - onerous operation |", md);
            Assert.Contains("| 1000 · IGV | 128.00 PEN |  | 23.04 PEN |", md);
            Assert.Contains("| 9997 · Exonerated | 30.00 PEN |  | 0.00 PEN |", md);
            // the signature is named, not printed
            Assert.Contains("digital signature (not printed)", md);
            Assert.DoesNotContain("SAMPLESIGNATUREVALUE", md);
        }

        [Fact]
        public void The_same_invoice_in_Spanish_says_it_in_the_words_of_SUNAT()
        {
            var md = Sample("pe-factura.xml", "es");
            Assert.StartsWith("# Factura electrónica F001-123", md);
            Assert.Contains("> 2.1 · 0101 (Venta interna)", md);
            Assert.Contains("(Monto en letras)", md);
            Assert.Contains("10 · Gravado - operación onerosa", md);
            Assert.Contains("| 9997 · Exonerado |", md);
        }

        [Fact]
        public void A_credit_note_says_its_reason_by_catalog_09_and_the_type_of_the_invoice_it_corrects()
        {
            var md = Sample("pe-nota-credito.xml");
            Assert.StartsWith("# Electronic credit note FC01-7", md);
            Assert.Contains("F001-123 (Electronic invoice)", md);
            Assert.Contains("01: Cancellation of the operation · Anulación de la operación", md);
            // a customer with a DNI says so
            Assert.Contains("- **Tax ID:** 00000001 (DNI)", md);
            Assert.Contains("- **Tax ID:** 20000000001 (RUC)", md);
            var es = Sample("pe-nota-credito.xml", "es");
            Assert.Contains("01: Anulación de la operación", es);
            Assert.DoesNotContain("Anulación de la operación · Anulación", es);
        }

        [Fact]
        public void Code_03_is_a_boleta_in_Peru_and_not_a_Colombian_contingency_invoice()
        {
            var xml = File.ReadAllText(Path.Combine(TestPaths.Samples, "pe-factura.xml")).Replace(">01</cbc:InvoiceTypeCode>", ">03</cbc:InvoiceTypeCode>");
            Assert.StartsWith("# Electronic sales receipt (boleta de venta) F001-123", Read(xml));
            // a type that SUNAT's table here does not have is said as it is, never as a Colombian one
            var other = File.ReadAllText(Path.Combine(TestPaths.Samples, "pe-factura.xml")).Replace(">01</cbc:InvoiceTypeCode>", ">02</cbc:InvoiceTypeCode>");
            Assert.StartsWith("# Invoice (type 02) F001-123", Read(other));
        }

        [Fact]
        public void A_file_without_the_SUNAT_attributes_is_read_like_any_other_UBL_file()
        {
            var xml = File.ReadAllText(Path.Combine(TestPaths.Samples, "pe-factura.xml"))
                .Replace("PE:SUNAT", "OTHER").Replace("urn:pe:gob:sunat", "urn:other");
            var md = Read(xml);
            // not recognised as Peruvian: the Colombian words and the check digit rule apply, nothing is invented
            Assert.DoesNotContain("(Domestic sale)", md);
            Assert.DoesNotContain("(Amount in words)", md);
        }

        [Fact]
        public void A_Colombian_invoice_with_a_Peruvian_customer_is_still_a_Colombian_invoice()
        {
            var md = Read("<Invoice xmlns=\"urn:oasis:names:specification:ubl:schema:xsd:Invoice-2\" xmlns:cac=\"urn:oasis:names:specification:ubl:schema:xsd:CommonAggregateComponents-2\" xmlns:cbc=\"urn:oasis:names:specification:ubl:schema:xsd:CommonBasicComponents-2\">"
                + "<cbc:ProfileID>DIAN 2.1: Factura Electrónica de Venta</cbc:ProfileID><cbc:ID>SETP1</cbc:ID><cbc:InvoiceTypeCode>03</cbc:InvoiceTypeCode><cbc:DocumentCurrencyCode>COP</cbc:DocumentCurrencyCode>"
                + "<cac:AccountingSupplierParty><cac:Party><cac:PartyTaxScheme><cbc:RegistrationName>Proveedor</cbc:RegistrationName><cbc:CompanyID schemeID=\"3\" schemeName=\"31\">900123456</cbc:CompanyID></cac:PartyTaxScheme></cac:Party></cac:AccountingSupplierParty>"
                + "<cac:AccountingCustomerParty><cac:Party><cac:PartyIdentification><cbc:ID schemeID=\"6\" schemeAgencyName=\"PE:SUNAT\">20000000002</cbc:ID></cac:PartyIdentification></cac:Party></cac:AccountingCustomerParty></Invoice>", "es");
            // the check digit of the Colombian issuer stays a check digit, and "03" is the Colombian contingency invoice, not a boleta
            Assert.Contains("900123456-3", md);
            Assert.Contains("contingencia del facturador", md);
            Assert.DoesNotContain("Boleta", md);
        }

        [Fact]
        public void A_legend_or_a_document_type_that_the_tables_do_not_have_is_printed_as_it_is()
        {
            var factura = File.ReadAllText(Path.Combine(TestPaths.Samples, "pe-factura.xml")).Replace("languageLocaleID=\"3000\"", "languageLocaleID=\"9999\"");
            Assert.Contains("0501002026030400000123 (9999)", Read(factura));
            var credit = File.ReadAllText(Path.Combine(TestPaths.Samples, "pe-nota-credito.xml")).Replace(">01</cbc:DocumentTypeCode>", ">99</cbc:DocumentTypeCode>");
            Assert.Contains("F001-123 (99)", Read(credit));
        }

        [Fact]
        public void The_folder_table_has_the_RUC_the_DNI_the_type_and_a_unique_code_so_that_a_copy_is_counted_once()
        {
            var folder = TestPaths.NewTempFolder();
            try
            {
                File.Copy(Path.Combine(TestPaths.Samples, "pe-factura.xml"), Path.Combine(folder, "F001-123.xml"));
                File.Copy(Path.Combine(TestPaths.Samples, "pe-factura.xml"), Path.Combine(folder, "copy of F001-123.xml"));
                File.Copy(Path.Combine(TestPaths.Samples, "pe-nota-credito.xml"), Path.Combine(folder, "FC01-7.xml"));
                var result = InvoiceTable.ReadFolder(folder);
                Assert.Equal(2, result.Rows.Count);
                var invoice = result.Rows.Single(r => r.Number == "F001-123");
                Assert.Equal("20000000001-01-F001-123", invoice.Cuf);
                Assert.Equal("20000000001", invoice.IssuerId);
                Assert.Equal("158.00", invoice.Base.Text);
                Assert.Equal("181.04", invoice.Payable.Text);
                Assert.Equal("PEN", invoice.Currency);
                var credit = result.Rows.Single(r => r.Number == "FC01-7");
                Assert.Equal("20000000001-07-FC01-7", credit.Cuf);
                Assert.True(credit.IsCreditNote);
                var skipped = Assert.Single(result.Skipped);
                Assert.Equal(InvoiceSkip.Duplicate, skipped.Reason);
                // the credit note is subtracted, per currency
                var pen = InvoiceTable.Totals(result).Single();
                Assert.Equal("PEN", pen.Currency);
                Assert.Equal(58.00m, pen.Sums[0]);
                Assert.Equal(63.04m, pen.Sums[4]);
                var md = InvoiceTable.ToMarkdown(result, XmlLabels.For("en"), "");
                Assert.Contains("| Electronic invoice |", md);
                Assert.Contains("00000001 (DNI)", md);
                Assert.DoesNotContain("20000000001-6", md);
            }
            finally { Directory.Delete(folder, true); }
        }
    }
}
