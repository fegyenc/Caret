            Assert.Contains("- **Tax base:** R$ 1470.00", md);
            Assert.Contains("- **IBS state: rate (effective) and value:** 0.10 % · 0.10 % · R$ 1.47", md);
            Assert.Contains("- **CBS: rate (effective) and value:** 0.90 % · 0.90 % · R$ 13.23", md);
            Assert.Contains("- **Total of the document with IBS and CBS:** R$ 1514.70", md);
        }

        [Fact]
        public void A_document_of_another_namespace_is_not_taken_for_an_NFSe()
        {
            var md = Read("<DPS xmlns=\"urn:another:standard\"><infDPS><nDPS>1</nDPS></infDPS></DPS>");
            Assert.DoesNotContain("National NFS-e standard", md);
        }

        // The official schemas of the national NFS-e import the standard schema of XML signatures, whose first lines are a DOCTYPE with a public identifier and a
        // web address: the schema check must read them (nothing is fetched) instead of saying that the schema cannot be used.
        [Fact]
        public void A_schema_that_imports_the_signature_schema_with_its_DOCTYPE_can_be_used()
        {
            var work = TestPaths.NewTempFolder();
            try
            {
                File.WriteAllText(Path.Combine(work, "sig.xsd"),
                    "<?xml version=\"1.0\" encoding=\"utf-8\"?>\n<!DOCTYPE schema PUBLIC \"-//W3C//DTD XMLSchema 200102//EN\" \"http://www.w3.org/2001/XMLSchema.dtd\"\n [\n <!ATTLIST schema xmlns:ds CDATA #FIXED \"http://www.w3.org/2000/09/xmldsig#\">\n <!ENTITY dsig 'http://www.w3.org/2000/09/xmldsig#'>\n ]>\n" +
                    "<schema xmlns=\"http://www.w3.org/2001/XMLSchema\" xmlns:ds=\"http://www.w3.org/2000/09/xmldsig#\" targetNamespace=\"http://www.w3.org/2000/09/xmldsig#\" elementFormDefault=\"qualified\"><element name=\"Signature\" type=\"string\"/></schema>");
                var main = Path.Combine(work, "main.xsd");
                File.WriteAllText(main,
                    "<xs:schema xmlns:xs=\"http://www.w3.org/2001/XMLSchema\" xmlns:ds=\"http://www.w3.org/2000/09/xmldsig#\" targetNamespace=\"urn:t\" xmlns=\"urn:t\" elementFormDefault=\"qualified\">" +
                    "<xs:import namespace=\"http://www.w3.org/2000/09/xmldsig#\" schemaLocation=\"sig.xsd\"/><xs:element name=\"a\"><xs:complexType><xs:sequence><xs:element name=\"b\" type=\"xs:string\"/><xs:element ref=\"ds:Signature\"/></xs:sequence></xs:complexType></xs:element></xs:schema>");
                var good = "<a xmlns=\"urn:t\"><b>x</b><Signature xmlns=\"http://www.w3.org/2000/09/xmldsig#\">s</Signature></a>";
                Assert.Equal(XmlSchemaState.Valid, XmlSchemaCheck.Run(good, new[] { main }).State);
                var bad = "<a xmlns=\"urn:t\"><Signature xmlns=\"http://www.w3.org/2000/09/xmldsig#\">s</Signature></a>";
                Assert.Equal(XmlSchemaState.Invalid, XmlSchemaCheck.Run(bad, new[] { main }).State);
            }
            finally { Directory.Delete(work, true); }
        }

        [Fact]
        public void A_schema_with_an_entity_that_expands_without_limit_is_refused_and_not_read_to_the_end()
        {
            var work = TestPaths.NewTempFolder();
            try
            {
                string Level(int n) => n == 0 ? "<!ENTITY e0 'aaaaaaaaaa'>" : $"<!ENTITY e{n} '{string.Concat(Enumerable.Repeat($"&e{n - 1};", 10))}'>";
                var dtd = string.Join("\n", Enumerable.Range(0, 8).Select(Level));
                var main = Path.Combine(work, "bomb.xsd");
                File.WriteAllText(main, $"<?xml version=\"1.0\"?>\n<!DOCTYPE xs:schema [\n{dtd}\n]>\n<xs:schema xmlns:xs=\"http://www.w3.org/2001/XMLSchema\" targetNamespace=\"urn:t\" xmlns=\"urn:t\"><xs:element name=\"a\" type=\"xs:string\" id=\"&e7;\"/></xs:schema>");
                var outcome = XmlSchemaCheck.Run("<a xmlns=\"urn:t\">x</a>", new[] { main });
                Assert.Equal(XmlSchemaState.Unusable, outcome.State);
            }
            finally { Directory.Delete(work, true); }
        }
    }
