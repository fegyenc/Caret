        [Fact]
        public void The_checks_use_the_formulas_of_the_schema()
        {
            var text = SampleText("br-nfse-nacional.xml");
            // the ISSQN is the base times the rate
            var iss = Read(text.Replace("<vISSQN>30.00</vISSQN>", "<vISSQN>35.00</vISSQN>"));
            Assert.Contains("The ISSQN is 35.00; the tax base 1500.00 times the rate 2.00 % is 30.00.", iss);
            // the total withheld is the sum of the withholdings of the declaration
            var ret = Read(text.Replace("<vTotalRet>0.00</vTotalRet>", "<vTotalRet>12.00</vTotalRet>"));
            Assert.Contains("The total withheld is 12.00; the withholdings of the declaration add up to 0.00.", ret);
            // the net value is the services less the discounts and the withholdings
            var net = Read(text.Replace("<vLiq>1500.00</vLiq>", "<vLiq>1400.00</vLiq>"));
            Assert.Contains("The net value is 1400.00; the value of the services less the discounts and the withholdings is 1500.00.", net);
            // the access key repeats the number, the registration of the issuer and the generating environment
            var number = Read(text.Replace("<nNFSe>456</nNFSe>", "<nNFSe>457</nNFSe>"));
            Assert.Contains("The access key has the number 456; the document says 457.", number);
            var issuer = Read(text.Replace("<emit><CNPJ>11222333000181</CNPJ>", "<emit><CNPJ>45997418000153</CNPJ>"));
            Assert.Contains("The access key has the registration 11222333000181; the issuer is 45997418000153.", issuer);
            var environment = Read(text.Replace("<ambGer>2</ambGer>", "<ambGer>1</ambGer>"));
            Assert.Contains("The access key says generating environment 2; the document says 1.", environment);
            // a rounding of a cent is not a finding
            Assert.Contains("found nothing", Read(text.Replace("<vISSQN>30.00</vISSQN>", "<vISSQN>30.01</vISSQN>")));
        }

        [Fact]
        public void The_IBS_and_CBS_the_system_computes_are_shown()
        {
            var computed = "<IBSCBS><cLocalidadeIncid>3550308</cLocalidadeIncid><xLocalidadeIncid>Sao Paulo</xLocalidadeIncid><valores><vBC>1470.00</vBC>" +
                "<uf><pIBSUF>0.10</pIBSUF><pAliqEfetUF>0.10</pAliqEfetUF></uf><mun><pIBSMun>0.00</pIBSMun><pAliqEfetMun>0.00</pAliqEfetMun></mun><fed><pCBS>0.90</pCBS><pAliqEfetCBS>0.90</pAliqEfetCBS></fed></valores>" +
                "<totCIBS><vTotNF>1514.70</vTotNF><gIBS><vIBSTot>1.47</vIBSTot><gIBSUFTot><vIBSUF>1.47</vIBSUF></gIBSUFTot><gIBSMunTot><vIBSMun>0.00</vIBSMun></gIBSMunTot></gIBS><gCBS><vCBS>13.23</vCBS></gCBS></totCIBS></IBSCBS>";
            var md = Read(SampleText("br-nfse-nacional.xml").Replace("<DPS versao", computed + "<DPS versao"));
