    // Brazil's national NFS-e (Services/Conversion/XmlNfse.cs): the NFS-e, the DPS and the events, read from the national schema v1.01. The samples in samples/
    // are invented and valid against that schema (checked with the schema package of the national portal).
    public class NfseTests
    {
        private const string Key = "35503082211222333000181000000000045626101234567890";

        private static string Sample(string name, string language = "en") =>
            DocumentConverter.Convert(Path.Combine(TestPaths.Samples, name), new ConversionOptions { Language = language }).Markdown;

        private static string Read(string xml, string language = "en")
        {
            var work = TestPaths.NewTempFolder();
            try
            {
                var path = Path.Combine(work, "nfse.xml");
                File.WriteAllText(path, xml, new UTF8Encoding(false));
                return DocumentConverter.Convert(path, new ConversionOptions { Language = language }).Markdown;
            }
            finally { Directory.Delete(work, true); }
        }

        private static string SampleText(string name) => File.ReadAllText(Path.Combine(TestPaths.Samples, name), Encoding.UTF8);

        [Fact]
        public void An_authorized_NFSe_says_what_it_is_who_issued_it_for_whom_and_the_values()
        {
            var md = Sample("br-nfse-nacional.xml");
            Assert.StartsWith("# NFS-e 456 · Empresa de Servicos Exemplo Ltda", md);
            Assert.Contains("> File: br-nfse-nacional.xml · National NFS-e standard 1.01 · 100 — NFS-e Gerada", md);
            Assert.Contains("- **Access key:** " + Key, md);
            Assert.Contains("- **Series and DPS number:** 1 / 123", md);
            Assert.Contains("- **Issuing municipality:** Sao Paulo · IBGE 3550308", md);
            // the codes in the words of the national schema, with the code first
            Assert.Contains("- **Environment:** 2 — Homologação", md);
            Assert.Contains("- **Generated by:** 2 — Sistema Nacional da NFS-e", md);
            Assert.Contains("- **Simples Nacional:** 3 — Optante - Microempresa ou Empresa de Pequeno Porte (ME/EPP)", md);
            Assert.Contains("- **CNPJ:** 11222333000181", md);
            Assert.Contains("- **Address:** Avenida de Teste 1000, Sala 12, Centro · IBGE 3550308 · SP · CEP 01310100", md);
            Assert.Contains("- **National tax code (cTribNac):** 010101 — Analise e desenvolvimento de sistemas", md);
            Assert.Contains("- **ISSQN taxation:** 1 — Operação tributável", md);
            Assert.Contains("- **ISSQN:** R$ 30.00", md);
            Assert.Contains("- **Net value:** R$ 1500.00", md);
            // the signature is named, not printed
            Assert.Contains("- **Signature:** digital signature (not printed)", md);
            Assert.DoesNotContain("U0FNUExFU0lHTkFUVVJF", md.Substring(0, md.IndexOf("## All fields", System.StringComparison.Ordinal)));
            Assert.Contains("The checks below found nothing.", md);
        }

